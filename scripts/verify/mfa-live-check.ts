/**
 * End-to-end MFA HTTP flow against a LIVE server.
 *
 * Run: bun scripts/verify/mfa-live-check.ts   (start the app first)
 *
 * ── WHY THIS EXISTS ──────────────────────────────────────────────────────────
 * The TOTP implementation was broken for its entire life: it HMACed the base32
 * TEXT instead of decoding it, so every code it produced was wrong. The unit
 * suite was green throughout, because RFC 6238 Appendix B's secret is an ASCII
 * key rather than base32 — the vectors tested a different argument convention
 * from the one production uses.
 *
 * Unit tests could not have caught it, and neither could the type checker. What
 * caught it was a person trying to enrol through the UI.
 *
 * So this script drives the ACTUAL HTTP endpoints, with a code generated by an
 * INDEPENDENT implementation — a second, deliberately naive TOTP written from
 * the RFC, sharing no code with src/lib/fgmp/mfa/. If the two disagree, the
 * server is wrong regardless of what its own tests say.
 *
 * It exercises the whole path: enrol -> verify-enrol -> challenge, and then the
 * same challenge with a BACKUP CODE, because those are two different verification
 * paths and only one of them had ever run.
 */

import { createHmac } from "node:crypto";

const BASE = process.env.FGMP_BASE_URL ?? "http://127.0.0.1:3000";

/**
 * The subset of the JSON these endpoints return that the probe reads. Written
 * out rather than `any` so a renamed field is a compile error here, not a
 * probe that silently checks `undefined` and prints PASS.
 */
interface MfaProbeResponse {
  secret?: string;
  enrolled?: boolean;
  code?: string;
  backupCodes?: string[];
  challengeToken?: string;
  verified?: boolean;
  method?: string;
}

// ── An INDEPENDENT TOTP implementation ───────────────────────────────────────
// Deliberately written from RFC 6238 with no import from the code under test.
// It shares nothing with src/lib/fgmp/mfa/totp.ts except the algorithm.

const ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZ234567";

function base32ToBytes(secret: string): Buffer {
  const clean = secret.toUpperCase().replace(/=+$/, "");
  let bits = 0;
  let value = 0;
  const out: number[] = [];
  for (const ch of clean) {
    const idx = ALPHABET.indexOf(ch);
    if (idx === -1) throw new Error(`bad base32 char ${ch}`);
    value = (value << 5) | idx;
    bits += 5;
    if (bits >= 8) {
      out.push((value >>> (bits - 8)) & 0xff);
      bits -= 8;
    }
  }
  return Buffer.from(out);
}

/** RFC 6238: HMAC over the TIME STEP, dynamic truncation, modulo. */
function referenceTotp(secret: string, unixSeconds: number, digits = 6): string {
  const counter = Buffer.alloc(8);
  counter.writeBigUInt64BE(BigInt(Math.floor(unixSeconds / 30)));
  const h = createHmac("sha1", base32ToBytes(secret)).update(counter).digest();
  const off = h[h.length - 1] & 0x0f;
  const bin =
    ((h[off] & 0x7f) << 24) |
    ((h[off + 1] & 0xff) << 16) |
    ((h[off + 2] & 0xff) << 8) |
    (h[off + 3] & 0xff);
  return String(bin % 10 ** digits).padStart(digits, "0");
}

interface Check {
  name: string;
  ok: boolean;
  detail: string;
}
const checks: Check[] = [];
function record(name: string, ok: boolean, detail: string): void {
  checks.push({ name, ok, detail });
  console.log(`${ok ? "PASS" : "FAIL"}  ${name}${detail ? ` — ${detail}` : ""}`);
}

async function post(path: string, body: unknown, cookie?: string) {
  const res = await fetch(`${BASE}${path}`, {
    method: "POST",
    headers: {
      "content-type": "application/json",
      ...(cookie ? { cookie } : {}),
    },
    body: JSON.stringify(body),
  });
  let json: MfaProbeResponse | null = null;
  try {
    json = (await res.json()) as MfaProbeResponse;
  } catch {
    /* empty body is fine */
  }
  return { status: res.status, json, setCookie: res.headers.get("set-cookie") };
}

async function main(): Promise<void> {
  const email = process.env.MFA_TEST_EMAIL;
  const password = process.env.MFA_TEST_PASSWORD;
  if (!email || !password) {
    console.error("Set MFA_TEST_EMAIL and MFA_TEST_PASSWORD.");
    process.exit(2);
  }

  // 1. Sign in to get a session cookie.
  const login = await post("/api/auth/callback/credentials", {
    email,
    password,
    csrfToken: process.env.MFA_TEST_CSRF ?? "",
    json: true,
  });
  const cookie = (login.setCookie ?? "").split(";")[0];
  if (!cookie) {
    console.error("Sign-in failed. Start the app and check MFA_TEST_EMAIL/PASSWORD.");
    process.exit(2);
  }
  record("sign in", true, cookie.slice(0, 24) + "…");

  // 2. Enrol — returns the base32 secret.
  const enrol = await post("/api/fgmp/mfa/enrol", {}, cookie);
  const secret = enrol.json?.secret;
  record(
    "POST /enrol returns a base32 secret",
    enrol.status === 200 && typeof secret === "string" && /^[A-Z2-7]{32,}$/.test(secret),
    `status ${enrol.status}, secret ${String(secret).slice(0, 8)}…`,
  );
  if (!secret) process.exit(1);

  // 3. THE DEFECT: a code from an INDEPENDENT implementation must be accepted.
  const code = referenceTotp(secret, Math.floor(Date.now() / 1000));
  const verify = await post("/api/fgmp/mfa/verify-enrol", { code }, cookie);
  record(
    "verify-enrol accepts an independently-computed code",
    verify.status === 200 && verify.json?.enrolled === true,
    `status ${verify.status} code=${code} ${verify.json?.code ?? ""}`,
  );
  const backupCodes: string[] = verify.json?.backupCodes ?? [];
  record("backup codes issued once", backupCodes.length === 10, `${backupCodes.length} codes`);

  // 4. Status reflects the enrolment.
  const status = await fetch(`${BASE}/api/fgmp/mfa/status`, { headers: { cookie } });
  const statusJson = await status.json();
  record(
    "GET /status shows enabled",
    status.status === 200 && statusJson.enabled === true && statusJson.backupCodesRemaining === 10,
    `enabled=${statusJson.enabled} remaining=${statusJson.backupCodesRemaining}`,
  );

  // 5. Challenge path — re-authenticate, then complete with a fresh code.
  const reauth = await post("/api/auth/callback/credentials", {
    email,
    password,
    csrfToken: process.env.MFA_TEST_CSRF ?? "",
    json: true,
  });
  const cookie2 = (reauth.setCookie ?? "").split(";")[0];
  const pending = await post("/api/fgmp/mfa/challenge-request", {}, cookie2);
  const token = pending.json?.challengeToken;
  record(
    "pending session can request a challenge",
    pending.status === 200 && typeof token === "string" && token.length > 10,
    `status ${pending.status}`,
  );

  if (token) {
    const fresh = referenceTotp(secret, Math.floor(Date.now() / 1000));
    const done = await post("/api/fgmp/mfa/challenge", { challengeToken: token, code: fresh }, cookie2);
    record(
      "challenge accepted with an independently-computed code",
      done.status === 200 && done.json?.verified === true,
      `status ${done.status} method=${done.json?.method ?? "-"} ${done.json?.code ?? ""}`,
    );

    // 6. The OTHER verification path: a backup code.
    const reauth2 = await post("/api/auth/callback/credentials", {
      email, password, csrfToken: process.env.MFA_TEST_CSRF ?? "", json: true,
    });
    const cookie3 = (reauth2.setCookie ?? "").split(";")[0];
    const p2 = await post("/api/fgmp/mfa/challenge-request", {}, cookie3);
    if (p2.json?.challengeToken) {
      const used = await post(
        "/api/fgmp/mfa/challenge",
        { challengeToken: p2.json.challengeToken, code: backupCodes[0] },
        cookie3,
      );
      record(
        "challenge accepted with a BACKUP CODE",
        used.status === 200 && used.json?.method === "backup",
        `status ${used.status} method=${used.json?.method ?? "-"} ${used.json?.code ?? ""}`,
      );

      // Replay must fail — single use, enforced by the database.
      const reauth3 = await post("/api/auth/callback/credentials", {
        email, password, csrfToken: process.env.MFA_TEST_CSRF ?? "", json: true,
      });
      const cookie4 = (reauth3.setCookie ?? "").split(";")[0];
      const p3 = await post("/api/fgmp/mfa/challenge-request", {}, cookie4);
      if (p3.json?.challengeToken) {
        const replay = await post(
          "/api/fgmp/mfa/challenge",
          { challengeToken: p3.json.challengeToken, code: backupCodes[0] },
          cookie4,
        );
        record(
          "a REPLAYED backup code is refused",
          replay.status !== 200,
          `status ${replay.status} ${replay.json?.code ?? ""}`,
        );
      }
    }
  }

  const failed = checks.filter((c) => !c.ok);
  console.log(`\n${checks.length - failed.length}/${checks.length} checks passed`);
  process.exit(failed.length === 0 ? 0 : 1);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
