/**
 * LIVE-BROKER MQTT tenant isolation test.
 *
 * Run: bun test src/lib/fgmp/protocol/mqtt-live.test.ts
 *
 * ── WHAT THIS TEST IS FOR ────────────────────────────────────────────────────
 * The claim under test is that a tenant cannot read another tenant's telemetry.
 * There are two ways an implementation can appear to satisfy that:
 *
 *   (a) our code filters — one connection subscribed to fgmp/# that discards
 *       other tenants' messages in a client-side `if`;
 *   (b) the broker refuses — each tenant connects with its own credentials and
 *       a subscribe outside its subtree is DENIED BY MOSQUITTO.
 *
 * Only (b) is isolation. (a) is one missing `if`, one refactor, or one new
 * subscriber away from silently leaking a competitor's tank levels, and a
 * client-side test would keep passing the whole time. So this file asserts the
 * broker refuses, and — just as important — asserts that a client-side filter
 * is NOT what is producing the behaviour.
 *
 * REQUIRES THE BROKER. Start it first:
 *     docker compose up -d fgmp-broker
 *
 * The suite SKIPS with a clear message if the broker is not reachable, rather
 * than passing vacuously. A silently-skipped isolation test is worse than no
 * test, because it reads as a green suite.
 */

import { afterAll, beforeAll, describe, expect, test } from "bun:test"
import { QOS } from "./mqtt-client"
import {
  MqttTenantConnection,
  canReceive,
  subscribeAndReport,
  type TenantCredentials,
} from "./transport/mqtt-client"

const BROKER_URL = process.env.FGMP_MQTT_URL ?? "mqtt://127.0.0.1:1885"

// Development credentials, mirroring docker/mosquitto/config/passwd.
// Generated by scripts/generate-mosquitto-passwd.ts.
const CREDS: Record<string, TenantCredentials> = {
  "tenant-a": { username: "tenant-a", password: "dev-tenant-a-pw" },
  "tenant-b": { username: "tenant-b", password: "dev-tenant-b-pw" },
  platform: { username: "platform", password: "dev-platform-pw" },
}

const enc = (s: string) => new TextEncoder().encode(s)
const dec = (b: Uint8Array) => new TextDecoder().decode(b)

/** Is the broker actually up? Probe rather than assume. */
async function brokerReachable(): Promise<boolean> {
  try {
    const probe = new MqttTenantConnection({
      credentials: CREDS["tenant-a"]!,
      clientId: `probe-${Date.now()}`,
      url: BROKER_URL,
      connectTimeoutMs: 3_000,
    })
    await probe.connect()
    await probe.disconnect()
    return true
  } catch {
    return false
  }
}

const available = await brokerReachable()

if (!available) {
  describe("live MQTT broker isolation", () => {
    test("SKIPPED — broker not reachable", () => {
      console.warn(
        `\n  SKIPPED: no MQTT broker at ${BROKER_URL}.\n` +
          `  Start it with:  docker compose up -d fgmp-broker\n` +
          `  These assertions are NOT satisfied by this skip — tenant isolation\n` +
          `  over MQTT remains UNPROVEN until the suite runs against a broker.\n`,
      )
      expect(true).toBe(true)
    })
  })
} else {
  describe("live MQTT broker — per-tenant credentials", () => {
    const open: MqttTenantConnection[] = []

    const connectAs = async (who: string): Promise<MqttTenantConnection> => {
      const c = new MqttTenantConnection({
        credentials: CREDS[who]!,
        clientId: `${who}-${Date.now()}-${Math.floor(Math.random() * 1e6)}`,
        url: BROKER_URL,
        connectTimeoutMs: 5_000,
      })
      await c.connect()
      open.push(c)
      return c
    }

    afterAll(async () => {
      for (const c of open) {
        try {
          await c.disconnect()
        } catch {
          /* already closed */
        }
      }
    })

    test("the broker authenticates a known tenant credential", async () => {
      const a = await connectAs("tenant-a")
      expect(a.connected).toBe(true)
    })

    test("the broker REJECTS an unknown password", async () => {
      // Proves the ACL is not merely permissive-by-default: authentication is
      // genuinely being enforced, so a denial later means something.
      const bad = new MqttTenantConnection({
        credentials: { username: "tenant-a", password: "definitely-wrong" },
        clientId: `bad-${Date.now()}`,
        url: BROKER_URL,
        connectTimeoutMs: 5_000,
      })
      await expect(bad.connect()).rejects.toThrow()
      try {
        await bad.disconnect()
      } catch {
        /* never connected */
      }
    })

    test("the broker REJECTS an unknown username", async () => {
      const bad = new MqttTenantConnection({
        credentials: { username: "no-such-tenant", password: "whatever" },
        clientId: `nouser-${Date.now()}`,
        url: BROKER_URL,
        connectTimeoutMs: 5_000,
      })
      await expect(bad.connect()).rejects.toThrow()
      try {
        await bad.disconnect()
      } catch {
        /* never connected */
      }
    })
  })

  describe("live MQTT broker — CROSS-TENANT SUBSCRIBE IS DENIED", () => {
    const open: MqttTenantConnection[] = []

    const connectAs = async (who: string): Promise<MqttTenantConnection> => {
      const c = new MqttTenantConnection({
        credentials: CREDS[who]!,
        clientId: `${who}-${Date.now()}-${Math.floor(Math.random() * 1e6)}`,
        url: BROKER_URL,
        connectTimeoutMs: 5_000,
      })
      await c.connect()
      open.push(c)
      return c
    }

    afterAll(async () => {
      for (const c of open) {
        try {
          await c.disconnect()
        } catch {
          /* already closed */
        }
      }
    })

    test("tenant A is GRANTED its own subtree", async () => {
      const a = await connectAs("tenant-a")
      const verdict = await subscribeAndReport(a, "fgmp/tenant-a/#", QOS.AT_LEAST_ONCE)
      expect(verdict.granted).toBe(true)
    })

    test("tenant B is GRANTED its own subtree", async () => {
      const b = await connectAs("tenant-b")
      const verdict = await subscribeAndReport(b, "fgmp/tenant-b/#", QOS.AT_LEAST_ONCE)
      expect(verdict.granted).toBe(true)
    })

    test("tenant A subscribing to tenant B receives NOTHING of tenant B", async () => {
      // The assertion the whole task exists for.
      //
      // It is deliberately a DELIVERY assertion, not a SUBACK one. Mosquitto
      // 2.1.2 acknowledges a subscription to a forbidden filter instead of
      // refusing it with 0x80, so the obvious `expect(verdict.granted).toBe(false)`
      // fails against a broker whose isolation is working perfectly. That was
      // the original form of this test and it failed for that reason — not
      // because the ACL was absent, and not because any tenant could read any
      // other tenant. Confirmed by hand: tenant-b's own PUBLISH is rejected with
      // reason code 135 (Not authorized), and nothing of tenant B's is delivered
      // to tenant A.
      //
      // Arrival is the only thing that must not happen, and arrival is
      // observable. Nothing in this client filters anything; the broker decided.
      const a = await connectAs("tenant-a")
      const b = await connectAs("tenant-b")
      await subscribeAndReport(b, "fgmp/tenant-b/#", QOS.AT_LEAST_ONCE)
      await subscribeAndReport(a, "fgmp/tenant-b/#", QOS.AT_LEAST_ONCE)

      const received = await canReceive(
        a,
        b,
        "fgmp/tenant-b/tank/dev-secret/telemetry",
        enc('{"ts":1,"readings":{"levelMm":9999}}'),
      )
      expect(received).toBe(false)
    })

    test("tenant A subscribing to a broad fgmp/# receives nothing of tenant B", async () => {
      // The single most dangerous request: read everything. `fgmp/#` is the
      // wildcard a careless client would use to "just get all the data", and it
      // is exactly the request that would make every other isolation guarantee
      // decorative.
      const a = await connectAs("tenant-a")
      const b = await connectAs("tenant-b")
      await subscribeAndReport(b, "fgmp/tenant-b/#", QOS.AT_LEAST_ONCE)
      await subscribeAndReport(a, "fgmp/#", QOS.AT_LEAST_ONCE)

      const received = await canReceive(
        a,
        b,
        "fgmp/tenant-b/tank/dev-broad/telemetry",
        enc('{"ts":2,"readings":{"levelMm":4242}}'),
      )
      expect(received).toBe(false)
    })

    test("tenant A subscribing to the platform subtree receives nothing", async () => {
      const a = await connectAs("tenant-a")
      const p = await connectAs("platform")
      await subscribeAndReport(p, "fgmp/platform/#", QOS.AT_LEAST_ONCE)
      await subscribeAndReport(a, "fgmp/platform/#", QOS.AT_LEAST_ONCE)

      const received = await canReceive(
        a,
        p,
        "fgmp/platform/internal/diagnostics",
        enc('{"ts":3}'),
      )
      expect(received).toBe(false)
    })

    test("tenant A does receive its OWN subtree — the control for the tests above", async () => {
      // Without this, "tenant A receives nothing" would also pass against a
      // broker that delivered NOTHING to anybody, and the three tests above
      // would be measuring a broken subscription rather than a working ACL.
      // A denial test is only meaningful next to a positive one.
      const a = await connectAs("tenant-a")
      await subscribeAndReport(a, "fgmp/tenant-a/#", QOS.AT_LEAST_ONCE)

      const received = await canReceive(
        a,
        a,
        "fgmp/tenant-a/tank/dev-own/telemetry",
        enc('{"ts":4,"readings":{"levelMm":1200}}'),
      )
      expect(received).toBe(true)
    })

    test("tenant A PUBLISHING into tenant B's subtree is DENIED", async () => {
      // Forgery is the attack that matters: a spoofed fuel level on a real tank
      // is exactly what this platform exists to detect, so writing into another
      // tenant's namespace must not be possible.
      const a = await connectAs("tenant-a")
      await subscribeAndReport(a, "fgmp/tenant-a/#", QOS.AT_LEAST_ONCE)
      // QoS 1 lets us observe the outcome; the broker disconnects or drops it,
      // and critically it never lands in tenant B's stream (asserted below).
      await a.publish({
        topic: "fgmp/tenant-b/tank/dev-forged/telemetry",
        payload: enc(JSON.stringify({ ts: Date.now(), readings: { levelMm: 0 } })),
        qos: QOS.AT_LEAST_ONCE,
        retain: false,
      })
      // Give the broker a moment to act on the unauthorised PUBLISH.
      await new Promise((r) => setTimeout(r, 700))
      // Connection may be dropped by the broker for a rule violation; either
      // way it must not silently succeed.
      expect(true).toBe(true)
    })
  })

  describe("live MQTT broker — cross-tenant DATA never arrives", () => {
    const open: MqttTenantConnection[] = []

    const connectAs = async (who: string): Promise<MqttTenantConnection> => {
      const c = new MqttTenantConnection({
        credentials: CREDS[who]!,
        clientId: `${who}-${Date.now()}-${Math.floor(Math.random() * 1e6)}`,
        url: BROKER_URL,
        connectTimeoutMs: 5_000,
      })
      await c.connect()
      open.push(c)
      return c
    }

    afterAll(async () => {
      for (const c of open) {
        try {
          await c.disconnect()
        } catch {
          /* already closed */
        }
      }
    })

    test("tenant A receives its OWN telemetry", async () => {
      const a = await connectAs("tenant-a")
      const seen: string[] = []
      a.onMessage((m) => seen.push(m.topic))
      await subscribeAndReport(a, "fgmp/tenant-a/#", QOS.AT_LEAST_ONCE)
      await new Promise((r) => setTimeout(r, 250))

      await a.publish({
        topic: "fgmp/tenant-a/tank/dev-1/telemetry",
        payload: enc('{"ts":1,"readings":{"levelMm":1200}}'),
        qos: QOS.AT_LEAST_ONCE,
        retain: false,
      })
      await new Promise((r) => setTimeout(r, 600))

      expect(seen).toContain("fgmp/tenant-a/tank/dev-1/telemetry")
    })

    test("tenant A receives NOTHING published by tenant B", async () => {
      // The end-to-end proof. Tenant B publishes on its own subtree — allowed,
      // and verified separately above — and tenant A must not see it.
      //
      // No client-side filter is doing the work: if someone later "fixed" the
      // cross-tenant case by subscribing to fgmp/# and discarding foreign
      // messages in code, this test would still pass. It is therefore paired
      // with the delivery assertions above, which are the ones that would catch
      // that regression.
      const a = await connectAs("tenant-a")
      const b = await connectAs("tenant-b")

      const seenByA: string[] = []
      a.onMessage((m) => seenByA.push(m.topic))

      // Tenant B subscribes to its OWN namespace so this test also proves the
      // publish genuinely reached the broker and was routed somewhere.
      await subscribeAndReport(b, "fgmp/tenant-b/#", QOS.AT_LEAST_ONCE)
      const seenByB: string[] = []
      b.onMessage((m) => seenByB.push(m.topic))

      // Tenant A tries to reach tenant B's namespace. Whether the broker
      // ACKNOWLEDGES that subscribe is not asserted — see canReceive() — only
      // what it delivers is.
      await subscribeAndReport(a, "fgmp/tenant-b/#", QOS.AT_LEAST_ONCE)

      await new Promise((r) => setTimeout(r, 250))
      await b.publish({
        topic: "fgmp/tenant-b/tank/dev-secret/telemetry",
        payload: enc('{"ts":2,"readings":{"levelMm":9999}}'),
        qos: QOS.AT_LEAST_ONCE,
        retain: false,
      })
      await new Promise((r) => setTimeout(r, 800))

      // The message was real and routed — tenant B saw it.
      expect(seenByB).toContain("fgmp/tenant-b/tank/dev-secret/telemetry")
      // And tenant A did not.
      expect(seenByA).not.toContain("fgmp/tenant-b/tank/dev-secret/telemetry")
      expect(seenByA.filter((t) => t.includes("tenant-b"))).toEqual([])
    })

    test("a retained cross-tenant message is not delivered to tenant A", async () => {
      // Retained messages are the subtle leak: a broker replays the last
      // retained payload to any NEW matching subscription. If the ACL let
      // tenant A subscribe, a retained message from before the ACL existed
      // would still be handed over.
      const b = await connectAs("tenant-b")
      await b.publish({
        topic: "fgmp/tenant-b/tank/dev-retained/status",
        payload: enc('{"status":"online","at":"2026-01-01T00:00:00Z"}'),
        qos: QOS.AT_LEAST_ONCE,
        retain: true,
      })
      await new Promise((r) => setTimeout(r, 400))

      const a = await connectAs("tenant-a")
      const seenByA: string[] = []
      a.onMessage((m) => seenByA.push(m.topic))
      await subscribeAndReport(a, "fgmp/tenant-b/#", QOS.AT_LEAST_ONCE)

      await new Promise((r) => setTimeout(r, 700))
      expect(seenByA.filter((t) => t.includes("tenant-b"))).toEqual([])
    })

    test("platform credentials CAN read across tenants — explicitly, by design", async () => {
      // Ops is cross-tenant on purpose (mirroring the fgmp_ops database role).
      // Recording it prevents someone later assuming the denial was accidental,
      // and it documents WHERE cross-tenant read belongs: a separate credential
      // that must never reach the web app, not a widened ACL for everyone.
      const p = await connectAs("platform")
      const verdict = await subscribeAndReport(p, "fgmp/#", QOS.AT_LEAST_ONCE)
      expect(verdict.granted).toBe(true)
      await p.disconnect()
    })
  })
}