/**
 * Resolve a translation key for the given language. Falls back to English if
 * the key is missing from the Arabic dict, and to the raw key if missing
 * from both.
 */
export function translate(key: string, lang: Language): string {
  const entry = DICTIONARY[key];
  if (!entry) return key;
  return lang === "ar" ? entry.ar : entry.en;
}

/**
 * Translate a key, then interpolate `{name}` placeholders from `vars`.
 * Missing vars are left as-is; missing keys fall back to the raw key string
 * (same as `translate`). Useful for templates like `"{n} alarms"`.
 */
export function translateFmt(key: string, lang: Language, vars: Record<string, string | number>): string {
  let s = translate(key, lang);
  if (vars && typeof s === "string") {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
  }
  return s;
}
